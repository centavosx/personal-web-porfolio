// Copies the live site content into a local-only migration for the local database.
// Read only. The output is gitignored because this repo is public.
//
//   node --env-file=.env scripts/pull-seed.mjs
import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

const OUTPUT = "supabase/migrations/20261105000001_seed.sql";

const { SUPABASE_URL, SUPABASE_ANON_KEY, ABOUT_ID } = process.env;

if (!SUPABASE_URL || !SUPABASE_ANON_KEY || !ABOUT_ID) {
  throw new Error("Run with --env-file=.env so the live Supabase values are set");
}
if (SUPABASE_URL.includes("localhost")) {
  throw new Error("SUPABASE_URL points at the local stack, not the live project");
}

const client = createClient(SUPABASE_URL, SUPABASE_ANON_KEY);

const fetchRows = async (table, column) => {
  const { data, error } = await client.from(table).select("*").eq(column, ABOUT_ID);
  if (error) throw new Error(`${table}: ${error.message}`);
  console.log(`${table}: ${data.length} rows, columns: ${Object.keys(data[0] ?? {}).join(", ")}`);
  return data;
};

const toInsert = (table, rows) => {
  const json = JSON.stringify(rows);
  if (json.includes("$seed$")) throw new Error(`${table}: data contains the quote tag`);
  return `insert into public.${table}\nselect * from jsonb_populate_recordset(null::public.${table}, $seed$${json}$seed$::jsonb);\n`;
};

const statements = [toInsert("about", await fetchRows("about", "id"))];
for (const table of ["content", "service", "technology", "link", "address"]) {
  statements.push(toInsert(table, await fetchRows(table, "about_id")));
}

writeFileSync(OUTPUT, `-- Generated by scripts/pull-seed.mjs\n\n${statements.join("\n")}`);
console.log(`Wrote ${OUTPUT}`);
